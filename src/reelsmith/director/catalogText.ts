// RS-1210: the director's catalogue as compact markdown, generated into the reels-director SKILL.md between markers.
// The catalogue never changes between runs, and the skill is loaded whole at the start, while a tool result over 16k
// characters reaches an external agent only as an artifact pointer it must read in pieces (that is how the first agent
// run missed every effect, transition and sound). So reels_director_options carries only the project's own media.
import { MOVES, TEXT_STYLES } from './moves';
import { isClipTextStyle } from './textStyles';
import { DIRECTOR_EFFECTS, DIRECTOR_TRANSITIONS, effectParams } from './catalog';
import { DIRECTOR_SOUNDS } from './sfx';
import { REEL_LOOKS } from '../looks';
import type { MoveParam } from './moveKit';

export const CATALOG_START = '<!-- director-catalog:start (generated by src/reelsmith/director/sync-director-catalog.mts; do not edit by hand) -->';
export const CATALOG_END = '<!-- director-catalog:end -->';

const param = (p: MoveParam) => (p.type === 'number' && p.min !== undefined ? `${p.id}=${p.default} (${p.min}-${p.max})`
  : p.options ? `${p.id}=${p.default} (${p.options.length > 8 ? 'any transition id, or none' : p.options.join('|')})` : `${p.id}=${JSON.stringify(p.default)}`);

export function directorCatalogMarkdown(): string {
  const out: string[] = [];
  out.push('## Catalogue');
  out.push('');
  out.push('### Moves (one per section)');
  out.push('`id` · clips min-max · beats min-default-max · params — what it looks like. When to use it.');
  for (const m of MOVES) {
    const ps = m.params.length ? ` · ${m.params.map(param).join(', ')}` : '';
    out.push(`- \`${m.id}\` · ${m.clips.min}-${m.clips.max} clips · ${m.beats.min}-${m.beats.default}-${m.beats.max} beats${ps} — ${m.looks} ${m.use}`);
  }
  out.push('');
  out.push('### Text styles (a section\'s `text` + `textStyle`, or an overlay\'s `style`)');
  for (const t of TEXT_STYLES) {
    const ps = t.params.filter((p) => !['color', 'accent', 'size', 'x', 'y'].includes(p.id));
    out.push(`- \`${t.id}\` (≤${t.maxChars} chars${isClipTextStyle(t) ? ', drawn in the picture' : ''}${ps.length ? `; ${ps.map(param).join(', ')}` : ''}) — ${t.use}`);
  }
  out.push('All engine styles also take color, accent, size (0.4-2) and x/y (0-1).');
  out.push('');
  out.push('### Effects (a section\'s `effects`, up to 3; each with optional strength, region, timing, every, params)');
  const groups = new Map<string, string[]>();
  for (const e of DIRECTOR_EFFECTS) {
    const id = e.id.replace('builtin:fx-', '');
    const ps = effectParams(e.id).map((p) => p.id).join('/');
    groups.set(e.group, [...(groups.get(e.group) ?? []), `\`${id}\`${e.person ? ' (needs a person)' : ''}${ps ? ` [${ps}]` : ''}: ${e.use}`]);
  }
  for (const [g, list] of groups) out.push(`- **${g}**: ${list.join(' · ')}`);
  out.push('');
  out.push('### Transitions (a section\'s `transition`: how it comes in)');
  out.push(DIRECTOR_TRANSITIONS.map((t) => `\`${t.id}\`: ${t.use}`).join(' · '));
  out.push('');
  out.push('### Looks (plan `look`, or a section `look`)');
  out.push(REEL_LOOKS.map((l) => `\`${l.id}\` (${l.mood})`).join(' · '));
  out.push('');
  out.push('### Sounds (only for a section `sounds` entry; the usual ones are added automatically)');
  out.push(DIRECTOR_SOUNDS.map((s) => `\`${s.id}\``).join(' '));
  return out.join('\n');
}

/** SKILL.md with its catalogue section replaced by the current one. */
export function withCatalog(skill: string): string {
  const a = skill.indexOf(CATALOG_START), b = skill.indexOf(CATALOG_END);
  const block = `${CATALOG_START}\n${directorCatalogMarkdown()}\n${CATALOG_END}`;
  if (a < 0 || b < a) return `${skill.trimEnd()}\n\n${block}\n`;
  return `${skill.slice(0, a)}${block}${skill.slice(b + CATALOG_END.length)}`;
}
